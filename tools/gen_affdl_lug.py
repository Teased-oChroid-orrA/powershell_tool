#!/usr/bin/env python3
"""Regenerate lug-solver/src/affdl_data.rs from the digitized AFFDL-TR-69-42 Section 9 charts.

Source: `js/lug-math.js` of https://kaspercalc.com/LugPinAnalysis.html (its `CURVES` object and `FIG9_17`), which
digitizes the scanned figures point for point. The underlying charts are AFFDL-TR-69-42 Section 9 / Bruhn Chapter D1
(Melcon and Hoblit, 1953). The site states no licence for its arrays; the charts themselves come from a US Government
report. Save the file locally first, then:

    python3 tools/gen_affdl_lug.py path/to/lug-math.js > lug-solver/src/affdl_data.rs
"""
import json
import re
import sys

src = open(sys.argv[1]).read()
src = re.sub(r"//[^\n]*", "", src)


def block(name):
    m = re.search(r"var %s = \{" % name, src)
    i = m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        depth += {"{": 1, "}": -1}.get(src[j], 0)
        if depth == 0:
            return src[i : j + 1]
    raise SystemExit("unbalanced " + name)


def parse(text):
    return json.loads(re.sub(r"([{,]\s*)([A-Za-z_][A-Za-z_0-9]*)\s*:", r'\1"\2":', text))


curves = parse(block("CURVES"))
curves["fig9_17"] = parse(block("FIG9_17"))


def pts(a):
    return "&[" + ",".join("[%r,%r]" % (float(x), float(y)) for x, y in a) + "]"


def fam(f):
    return "Family { params: &[%s], curves: &[%s] }" % (",".join(repr(float(p)) for p in f["params"]), ",\n    ".join(pts(c) for c in f["curves"]))


out = ["//! GENERATED by tools/gen_affdl_lug.py - do not edit. Digitized AFFDL-TR-69-42 Section 9 charts (see `affdl.rs`).",
       "use crate::affdl::Family;", ""]
for key, const in [("fig9_2a", "FIG9_2A"), ("fig9_2b", "FIG9_2B"), ("fig9_3_cutA", "FIG9_3_CUT_A"), ("fig9_3_cutB", "FIG9_3_CUT_B"),
                   ("fig9_8u", "FIG9_8U"), ("fig9_8y", "FIG9_8Y"), ("fig9_10", "FIG9_10")]:
    out.append("pub static %s: &[[f64; 2]] = %s;" % (const, pts(curves[key])))
for key, const in [("fig9_3", "FIG9_3"), ("fig9_4b", "FIG9_4B"), ("fig9_4c", "FIG9_4C"), ("fig9_4d", "FIG9_4D"), ("fig9_17", "FIG9_17")]:
    out.append("pub static %s: Family = %s;" % (const, fam(curves[key])))
print("\n".join(out))
